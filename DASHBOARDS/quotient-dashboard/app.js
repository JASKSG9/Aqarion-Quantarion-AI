function currentCoordinateCount() {
  const freeRank = Number(parseNonnegativeInteger(
    freeRankInput.value,
    "Free rank",
  ));

  const torsion = parseTorsionInvariants(torsionInvariantsInput.value);

  return freeRank + torsion.length;
}

function coordinateNames() {
  const freeRank = Number(parseNonnegativeInteger(
    freeRankInput.value,
    "Free rank",
  ));

  const torsion = parseTorsionInvariants(torsionInvariantsInput.value);
  const names = [];

  for (let index = 0; index < freeRank; index += 1) {
    names.push(`f${index + 1}`);
  }

  for (let index = 0; index < torsion.length; index += 1) {
    names.push(`t${index + 1}`);
  }

  return names;
}

function updateBasisDisplay() {
  try {
    const names = coordinateNames();
    basisDisplay.textContent = names.length > 0
      ? names.join(", ")
      : "No ambient generators: G = 0";
  } catch (error) {
    basisDisplay.textContent = "Correct rank and torsion input to build a basis.";
  }
}

function createGeneratorRow(values = null) {
  let coordinateCount;

  try {
    coordinateCount = currentCoordinateCount();
  } catch (error) {
    showError(error.message);
    return;
  }

  if (coordinateCount === 0) {
    showError(
      "The zero group has no coordinate basis. Add free rank or torsion factors first.",
    );
    return;
  }

  state.generatorRows += 1;

  const row = document.createElement("div");
  row.className = "generator-row";
  row.dataset.generatorRow = String(state.generatorRows);

  const label = document.createElement("span");
  label.className = "generator-label";
  label.textContent = `h${state.generatorRows}`;

  const coordinates = document.createElement("div");
  coordinates.className = "coordinate-inputs";

  for (let index = 0; index < coordinateCount; index += 1) {
    const input = document.createElement("input");
    input.type = "text";
    input.inputMode = "numeric";
    input.value = values && values[index] !== undefined
      ? String(values[index])
      : "0";
    input.dataset.coordinateIndex = String(index);
    input.setAttribute("aria-label", `Generator coordinate ${index + 1}`);
    coordinates.appendChild(input);
  }

  const remove = document.createElement("button");
  remove.type = "button";
  remove.className = "remove-generator-button";
  remove.textContent = "Remove";
  remove.addEventListener("click", () => {
    row.remove();
  });

  row.append(label, coordinates, remove);
  subgroupGeneratorRows.appendChild(row);
}

function readExistingGeneratorRows() {
  const rows = [...subgroupGeneratorRows.querySelectorAll(".generator-row")];

  return rows.map((row) => {
    const inputs = [...row.querySelectorAll("input")];

    return inputs.map((input, index) =>
      parseInteger(input.value, `Subgroup coordinate ${index + 1}`),
    );
  });
}

function rebuildGeneratorRows(preserveExisting = true) {
  let oldValues = [];

  if (preserveExisting) {
    try {
      oldValues = readExistingGeneratorRows();
    } catch {
      oldValues = [];
    }
  }

  subgroupGeneratorRows.innerHTML = "";
  state.generatorRows = 0;

  if (oldValues.length === 0) {
    createGeneratorRow();
    return;
  }

  for (const values of oldValues) {
    createGeneratorRow(values);
  }
}

/* ---------- Quotient calculations ---------- */

function cyclicQuotient(n, d) {
  const reducedD = positiveModulo(d, n);
  const quotientOrder = gcdBigInt(n, reducedD);
  const subgroupOrder = n / quotientOrder;

  return {
    kind: "cyclic",
    ambient: `ℤ/${formatBigInt(n)}ℤ`,
    subgroup: `⟨${formatBigInt(reducedD)}⟩`,
    structure: quotientOrder === 1n
      ? "0"
      : `ℤ/${formatBigInt(quotientOrder)}ℤ`,
    freeRank: 0,
    torsionFactors: quotientOrder > 1n ? [quotientOrder] : [],
    finite: true,
    finiteOrder: quotientOrder,
    subgroupOrder,
    quotientOrder,
    n,
    d: reducedD,
    relationMatrix: [[n], [reducedD]],
    cyclic: true,
  };
}

function quotientFromPresentation(
  freeRank,
  torsionInvariants,
  subgroupGenerators,
) {
  const ambientDimension = freeRank + torsionInvariants.length;

  if (ambientDimension === 0) {
    return {
      kind: "general",
      ambient: "0",
      structure: "0",
      freeRank: 0,
      torsionFactors: [],
      finite: true,
      finiteOrder: 1n,
      subgroupGenerators,
      relationMatrix: [],
      diagonal: [],
      cyclic: true,
    };
  }

  const relationColumns = [];

  torsionInvariants.forEach((modulus, index) => {
    const column = Array.from(
      { length: ambientDimension },
      () => 0n,
    );

    column[freeRank + index] = modulus;
    relationColumns.push(column);
  });

  for (const generator of subgroupGenerators) {
    if (generator.length !== ambientDimension) {
      throw new Error(
        `Each subgroup generator needs ${ambientDimension} coordinates.`,
      );
    }

    relationColumns.push(generator.slice());
  }

  const relationMatrix = Array.from(
    { length: ambientDimension },
    (_, row) => relationColumns.map((column) => column[row]),
  );

  const diagonal = relationColumns.length === 0
    ? []
    : smithNormalFormDiagonal(relationMatrix);

  const relationRank = matrixRankRational(relationMatrix);
  const quotientFreeRank = ambientDimension - relationRank;
  const quotientTorsion = diagonal.filter((value) => value > 1n);

  if (!factorsDivideChain(diagonal)) {
    throw new Error(
      "Internal Smith normal form consistency check failed: "
      + "diagonal factors are not divisibility ordered.",
    );
  }

  const finite = quotientFreeRank === 0;
  const finiteOrder = finite
    ? quotientTorsion.reduce((product, value) => product * value, 1n)
    : null;

  const cyclic = (
    quotientFreeRank === 1 && quotientTorsion.length === 0
  ) || (
    quotientFreeRank === 0 && quotientTorsion.length <= 1
  ) || (
    quotientFreeRank === 0 && quotientTorsion.length === 0
  );

  return {
    kind: "general",
    ambient: formatAmbientGroup(freeRank, torsionInvariants),
    structure: formatGroupStructure(
      quotientFreeRank,
      quotientTorsion,
    ),
    freeRank: quotientFreeRank,
    torsionFactors: quotientTorsion,
    finite,
    finiteOrder,
    subgroupGenerators,
    relationMatrix,
    diagonal,
    relationRank,
    ambientDimension,
    cyclic,
    ambientFreeRank: freeRank,
    ambientTorsion: torsionInvariants,
  };
}

function runCyclicCalculation() {
  try {
    const n = parsePositiveInteger(cyclicN.value, "n");
    const d = parseInteger(cyclicD.value, "d");
    const result = cyclicQuotient(n, d);

    state.latestResult = result;
    renderResult(result);
  } catch (error) {
    showError(error.message);
  }
}

function runGeneralCalculation() {
  try {
    const freeRank = Number(parseNonnegativeInteger(
      freeRankInput.value,
      "Free rank",
    ));

    const torsionInvariants = parseTorsionInvariants(
      torsionInvariantsInput.value,
    );

    const subgroupGenerators = readExistingGeneratorRows();

    const result = quotientFromPresentation(
      freeRank,
      torsionInvariants,
      subgroupGenerators,
    );

    state.latestResult = result;
    renderResult(result);
  } catch (error) {
    showError(error.message);
  }
}

