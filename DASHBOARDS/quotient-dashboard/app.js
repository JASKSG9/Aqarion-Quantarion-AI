/* ---------- Basic exact integer helpers ---------- */

function absBigInt(value) {
  return value < 0n ? -value : value;
}

function gcdBigInt(a, b) {
  a = absBigInt(a);
  b = absBigInt(b);

  while (b !== 0n) {
    const remainder = a % b;
    a = b;
    b = remainder;
  }

  return a;
}

function lcmBigInt(a, b) {
  if (a === 0n || b === 0n) {
    return 0n;
  }

  return absBigInt((a / gcdBigInt(a, b)) * b);
}

function extendedGcd(a, b) {
  const signA = a < 0n ? -1n : 1n;
  const signB = b < 0n ? -1n : 1n;
  let oldR = absBigInt(a);
  let r = absBigInt(b);
  let oldS = 1n;
  let s = 0n;
  let oldT = 0n;
  let t = 1n;

  while (r !== 0n) {
    const quotient = oldR / r;

    [oldR, r] = [r, oldR - quotient * r];
    [oldS, s] = [s, oldS - quotient * s];
    [oldT, t] = [t, oldT - quotient * t];
  }

  return {
    g: oldR,
    x: oldS * signA,
    y: oldT * signB,
  };
}

function positiveModulo(a, n) {
  const result = a % n;
  return result < 0n ? result + n : result;
}

function cloneMatrix(matrix) {
  return matrix.map((row) => row.slice());
}

function zeroMatrix(rows, columns) {
  return Array.from(
    { length: rows },
    () => Array.from({ length: columns }, () => 0n),
  );
}

function identityMatrix(size) {
  const matrix = zeroMatrix(size, size);

  for (let i = 0; i < size; i += 1) {
    matrix[i][i] = 1n;
  }

  return matrix;
}

function matrixRankRational(inputMatrix) {
  const matrix = inputMatrix.map((row) =>
    row.map((entry) => ({
      numerator: entry,
      denominator: 1n,
    })),
  );

  const rows = matrix.length;
  const columns = rows === 0 ? 0 : matrix[0].length;
  let pivotRow = 0;
  let rank = 0;

  function normalizeFraction(value) {
    if (value.numerator === 0n) {
      return { numerator: 0n, denominator: 1n };
    }

    const divisor = gcdBigInt(value.numerator, value.denominator);
    const numerator = value.numerator / divisor;
    const denominator = value.denominator / divisor;

    return denominator < 0n
      ? { numerator: -numerator, denominator: -denominator }
      : { numerator, denominator };
  }

  function subtractFractions(left, right) {
    return normalizeFraction({
      numerator:
        left.numerator * right.denominator
        - right.numerator * left.denominator,
      denominator: left.denominator * right.denominator,
    });
  }

  function multiplyFractions(left, right) {
    return normalizeFraction({
      numerator: left.numerator * right.numerator,
      denominator: left.denominator * right.denominator,
    });
  }

  function divideFractions(left, right) {
    if (right.numerator === 0n) {
      throw new Error("Division by zero in rational rank calculation.");
    }

    return normalizeFraction({
      numerator: left.numerator * right.denominator,
      denominator: left.denominator * right.numerator,
    });
  }

  for (let column = 0; column < columns && pivotRow < rows; column += 1) {
    let candidate = pivotRow;

    while (
      candidate < rows
      && matrix[candidate][column].numerator === 0n
    ) {
      candidate += 1;
    }

    if (candidate === rows) {
      continue;
    }

    [matrix[pivotRow], matrix[candidate]] =
      [matrix[candidate], matrix[pivotRow]];

    const pivot = matrix[pivotRow][column];

    for (let j = column; j < columns; j += 1) {
      matrix[pivotRow][j] = divideFractions(matrix[pivotRow][j], pivot);
    }

    for (let row = 0; row < rows; row += 1) {
      if (row === pivotRow) {
        continue;
      }

      const coefficient = matrix[row][column];

      if (coefficient.numerator === 0n) {
        continue;
      }

      for (let j = column; j < columns; j += 1) {
        matrix[row][j] = subtractFractions(
          matrix[row][j],
          multiplyFractions(coefficient, matrix[pivotRow][j]),
        );
      }
    }

    pivotRow += 1;
    rank += 1;
  }

  return rank;
}

/* ---------- Smith normal form ---------- */

/*
This SNF routine uses exact BigInt row/column operations.

For dashboard-scale matrices, it repeatedly:
1. finds a nonzero minimum pivot in the active submatrix,
2. applies Euclidean row and column reduction,
3. clears a pivot row/column when possible,
4. restarts if the candidate pivot does not divide the remaining submatrix,
5. enforces a nonnegative pivot.

The displayed invariant factors are the nonzero diagonal entries > 1.
*/

function swapRows(matrix, first, second) {
  [matrix[first], matrix[second]] = [matrix[second], matrix[first]];
}

function swapColumns(matrix, first, second) {
  for (const row of matrix) {
    [row[first], row[second]] = [row[second], row[first]];
  }
}

function multiplyRow(matrix, rowIndex, scalar) {
  for (let column = 0; column < matrix[rowIndex].length; column += 1) {
    matrix[rowIndex][column] *= scalar;
  }
}

function multiplyColumn(matrix, columnIndex, scalar) {
  for (let row = 0; row < matrix.length; row += 1) {
    matrix[row][columnIndex] *= scalar;
  }
}

function addRowMultiple(matrix, targetRow, sourceRow, multiple) {
  for (let column = 0; column < matrix[targetRow].length; column += 1) {
    matrix[targetRow][column] += multiple * matrix[sourceRow][column];
  }
}

function addColumnMultiple(matrix, targetColumn, sourceColumn, multiple) {
  for (let row = 0; row < matrix.length; row += 1) {
    matrix[row][targetColumn] += multiple * matrix[row][sourceColumn];
  }
}

function findSmallestNonzero(matrix, start) {
  let candidate = null;

  for (let row = start; row < matrix.length; row += 1) {
    for (let column = start; column < matrix[0].length; column += 1) {
      const value = matrix[row][column];

      if (value === 0n) {
        continue;
      }

      if (
        candidate === null
        || absBigInt(value) < absBigInt(candidate.value)
      ) {
        candidate = { row, column, value };
      }
    }
  }

  return candidate;
}

function findNonDivisibleEntry(matrix, start, pivot) {
  for (let row = start; row < matrix.length; row += 1) {
    for (let column = start; column < matrix[0].length; column += 1) {
      if (matrix[row][column] % pivot !== 0n) {
        return { row, column };
      }
    }
  }

  return null;
}

function smithNormalFormDiagonal(inputMatrix) {
  if (inputMatrix.length === 0) {
    return [];
  }

  if (inputMatrix[0].length === 0) {
    return [];
  }

  const matrix = cloneMatrix(inputMatrix);
  const rows = matrix.length;
  const columns = matrix[0].length;
  const diagonal = [];

  let pivotIndex = 0;

  while (pivotIndex < rows && pivotIndex < columns) {
    let smallest = findSmallestNonzero(matrix, pivotIndex);

    if (smallest === null) {
      break;
    }

    swapRows(matrix, pivotIndex, smallest.row);
    swapColumns(matrix, pivotIndex, smallest.column);

    let stabilized = false;

    while (!stabilized) {
      stabilized = true;

      for (let row = pivotIndex + 1; row < rows; row += 1) {
        if (matrix[row][pivotIndex] === 0n) {
          continue;
        }

        const pivot = matrix[pivotIndex][pivotIndex];
        const value = matrix[row][pivotIndex];
        const quotient = value / pivot;

        addRowMultiple(matrix, row, pivotIndex, -quotient);

        if (
          absBigInt(matrix[row][pivotIndex])
          < absBigInt(matrix[pivotIndex][pivotIndex])
          && matrix[row][pivotIndex] !== 0n
        ) {
          swapRows(matrix, row, pivotIndex);
        }

        stabilized = false;
      }

      for (let column = pivotIndex + 1; column < columns; column += 1) {
        if (matrix[pivotIndex][column] === 0n) {
          continue;
        }

        const pivot = matrix[pivotIndex][pivotIndex];
        const value = matrix[pivotIndex][column];
        const quotient = value / pivot;

        addColumnMultiple(matrix, column, pivotIndex, -quotient);

        if (
          absBigInt(matrix[pivotIndex][column])
          < absBigInt(matrix[pivotIndex][pivotIndex])
          && matrix[pivotIndex][column] !== 0n
        ) {
          swapColumns(matrix, column, pivotIndex);
        }

        stabilized = false;
      }

      if (matrix[pivotIndex][pivotIndex] === 0n) {
        smallest = findSmallestNonzero(matrix, pivotIndex);

        if (smallest === null) {
          break;
        }

        swapRows(matrix, pivotIndex, smallest.row);
        swapColumns(matrix, pivotIndex, smallest.column);
        stabilized = false;
      }

      if (!stabilized) {
        continue;
      }

      const pivot = matrix[pivotIndex][pivotIndex];

      if (pivot === 0n) {
        break;
      }

      const nonDivisible = findNonDivisibleEntry(
        matrix,
        pivotIndex + 1,
        pivot,
      );

      if (nonDivisible !== null) {
        /*
        Bring a nondivisible entry into the pivot row by adding its row to
        the pivot row, then repeat Euclidean clearing. This decreases the
        effective pivot divisor until it divides the submatrix.
        */
        addRowMultiple(
          matrix,
          pivotIndex,
          nonDivisible.row,
          1n,
        );

        if (matrix[pivotIndex][pivotIndex] === 0n) {
          swapColumns(matrix, pivotIndex, nonDivisible.column);
        }

        stabilized = false;
      }
    }

    if (matrix[pivotIndex][pivotIndex] === 0n) {
      break;
    }

    if (matrix[pivotIndex][pivotIndex] < 0n) {
      multiplyRow(matrix, pivotIndex, -1n);
    }

    for (let row = pivotIndex + 1; row < rows; row += 1) {
      const pivot = matrix[pivotIndex][pivotIndex];

      if (matrix[row][pivotIndex] !== 0n) {
        const quotient = matrix[row][pivotIndex] / pivot;
        addRowMultiple(matrix, row, pivotIndex, -quotient);
      }
    }

    for (let column = pivotIndex + 1; column < columns; column += 1) {
      const pivot = matrix[pivotIndex][pivotIndex];

      if (matrix[pivotIndex][column] !== 0n) {
        const quotient = matrix[pivotIndex][column] / pivot;
        addColumnMultiple(matrix, column, pivotIndex, -quotient);
      }
    }

    diagonal.push(absBigInt(matrix[pivotIndex][pivotIndex]));
    pivotIndex += 1;
  }

  return diagonal.filter((value) => value !== 0n);
}

/* ---------- Parsing and representation ---------- */

function parseInteger(value, fieldName) {
  const text = String(value).trim();

  if (!/^-?d+$/.test(text)) {
    throw new Error(`${fieldName} must be an integer.`);
  }

  return BigInt(text);
}

function parseNonnegativeInteger(value, fieldName) {
  const parsed = parseInteger(value, fieldName);

  if (parsed < 0n) {
    throw new Error(`${fieldName} must be nonnegative.`);
  }

  return parsed;
}

function parsePositiveInteger(value, fieldName) {
  const parsed = parseInteger(value, fieldName);

  if (parsed <= 0n) {
    throw new Error(`${fieldName} must be positive.`);
  }

  return parsed;
}

function parseTorsionInvariants(text) {
  const trimmed = text.trim();

  if (trimmed === "") {
    return [];
  }

  const values = trimmed
    .split(",")
    .map((entry) => entry.trim())
    .filter((entry) => entry.length > 0)
    .map((entry, index) => {
      const value = parseInteger(entry, `Torsion invariant ${index + 1}`);

      if (value <= 1n) {
        throw new Error(
          `Torsion invariant ${index + 1} must be an integer greater than 1.`,
        );
      }

      return value;
    });

  return values;
}

function formatBigInt(value) {
  return value.toString();
}

function formatTorsionFactor(value) {
  return `ℤ/${formatBigInt(value)}ℤ`;
}

function formatGroupStructure(freeRank, torsionFactors) {
  const terms = [];

  if (freeRank === 1) {
    terms.push("ℤ");
  } else if (freeRank > 1) {
    terms.push(`ℤ^${freeRank}`);
  }

  for (const factor of torsionFactors) {
    if (factor > 1n) {
      terms.push(formatTorsionFactor(factor));
    }
  }

  return terms.length > 0 ? terms.join(" ⊕ ") : "0";
}

function formatAmbientGroup(freeRank, torsionFactors) {
  return formatGroupStructure(freeRank, torsionFactors);
}

function factorsDivideChain(factors) {
  for (let index = 0; index + 1 < factors.length; index += 1) {
    if (factors[index + 1] % factors[index] !== 0n) {
      return false;
    }
  }

  return true;
}

